"""Numbers for the ICCE 2027 camera-ready from the Kaggle review run (JOB = "review"), as LaTeX macros.

    python experiments/review_numbers.py review_results.zip            # or the unpacked folder
    -> sim_out/review_numbers/review_numbers.tex (+ .json with every value and where it came from)

Macros
  \\XiphEfiveMax          largest E5 max leak (model and hardware form) over the six Xiph sequences
  \\XiphPubMin, \\XiphPubMax  the published schemes' max leak, each averaged over the six sequences: lowest, highest
  \\SmSources             sources of the size-matching run (synthetic scene excluded)
  \\SmExact               % of E5 segments placed exactly by the assignment attacker, pooled
  \\SmLeak, \\SmOld        best size-matching attack's leak; the old E2 frame's own leak (both vs the new frame)
  \\SmGain                mean gain over the old E2 frame [95 % CI]
  \\SmMotion              "motion correlation a; true order b": does the attacker see what changed
Every value is computed from the run's JSON files; nothing is typed by hand.
"""
import argparse
import io
import json
import sys
import zipfile
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "experiments"))
from benchmark_suite import bootstrap_ci   # noqa: E402

PUBLISHED = ("VanDroogenbroeck", "Kishore", "Auer", "Hirose RI=1", "Hirose RI=4")
E5 = ("E5 (v2)", "E5 (v3, hw)")


def load(src):
    """{relative path: parsed JSON} for every .json under src (zip or folder)."""
    out = {}
    p = Path(src)
    if p.suffix == ".zip":
        with zipfile.ZipFile(p) as z:
            for n in z.namelist():
                if n.endswith(".json"):
                    out[n] = json.load(io.TextIOWrapper(z.open(n), encoding="utf-8"))
    else:
        for f in p.rglob("*.json"):
            out[str(f.relative_to(p))] = json.loads(f.read_text())
    return out


def f2(x):
    return f"{x:.2f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src")
    ap.add_argument("--out", default="sim_out/review_numbers")
    a = ap.parse_args()
    files = load(a.src)
    bench = {Path(k).stem: v for k, v in files.items() if "benchmark_suite" in k and "schemes" in v}
    size = {Path(k).stem: v for k, v in files.items()
            if "e5_size_match" in k and "rows" in v and Path(k).stem != "summary"}
    vals, src = {}, {}
    if bench:
        e5 = max(bench[s]["schemes"][n]["max_leak"] for s in bench for n in E5)
        pub = {n: float(np.mean([bench[s]["schemes"][n]["max_leak"] for s in bench])) for n in PUBLISHED}
        vals.update(XiphEfiveMax=f2(e5), XiphPubMin=f2(min(pub.values())), XiphPubMax=f2(max(pub.values())))
        src["xiph"] = dict(sequences=sorted(bench), e5_max=e5, published_mean=pub)
    real = {k: v for k, v in size.items() if v["source"] != "synthetic"}
    if real:
        rows = [r for v in real.values() for r in v["rows"]]
        best = [r[r["best_attack"]]["leak"] for r in rows]
        gain = [r["gain"] for r in rows]
        lo, hi = bootstrap_ci(gain)
        mo = [max(r[k]["motion"] for k in ("rank_bytes", "assign_nz")) for r in rows]
        mo_true = [r["oracle"]["motion"] for r in rows]
        vals.update(SmSources=str(len(real)),
                    SmExact=f"{100 * np.mean([r['assign_nz']['exact'] for r in rows]):.0f}",
                    SmLeak=f2(np.mean(best)), SmOld=f2(np.mean([r["e2_old"]["leak"] for r in rows])),
                    SmGain=f"${np.mean(gain):+.2f}$ [${lo:+.2f}$, ${hi:+.2f}$]",
                    SmMotion=f"motion correlation ${np.mean(mo):.2f}$; true order ${np.mean(mo_true):.2f}$")
        src["size_match"] = dict(sources=sorted(real), rows=len(rows), gain_max=float(max(gain)),
                                 per_source={k: v["summary"] for k, v in real.items()})
    if not vals:
        raise SystemExit(f"{a.src}: no benchmark_suite or e5_size_match results found")
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    tex = ["% generated by experiments/review_numbers.py from " + Path(a.src).name + " -- do not edit"]
    tex += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in vals.items()]
    (out / "review_numbers.tex").write_text("\n".join(tex) + "\n")
    (out / "review_numbers.json").write_text(json.dumps(dict(values=vals, sources=src), indent=1))
    print("\n".join(tex))


if __name__ == "__main__":
    main()
